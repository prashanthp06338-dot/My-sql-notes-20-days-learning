USE da8;

CREATE TABLE EMPLOYEES(
EMPID CHAR(5),
FNAME VARCHAR(50),
LNAME VARCHAR(30),
AGE INT,
DOJ DATE,
ADDRESS TINYTEXT,
DEPT VARCHAR(20));

ALTER TABLE EMPLOYEES MODIFY FNAME VARCHAR (30);
ALTER TABLE EMPLOYEES ADD LOCATION TINYTEXT;

-- HOW TO ADD A COLUMN AFTER A PARTICULAR COLUMN
-- SYNTAX:- ALTER TABLE TABLE-NAME ADD COLUMN-NAME DATATYPE(SIZE) AFTER SPECIFIED-COLUMN-NAME


ALTER TABLE EMPLOYEES ADD PFID INT AFTER EMPID;
DESC EMPLOYEES;



-- ALTER TABLE EMPLOYEES ADD LOCATION TINYTEXT;
-- ALTER TABLE TABLE-NAME ADD COLUMN-NAME DATATYPE(SIZE) FIRST;



ALTER TABLE EMPLOYEES ADD COMPANY_NAME TEXT FIRST;


-- SYNTAX
-- HOW TO CHANGE COLUMN NAME
-- ALTER TABLE TABLE-NAME CHANGE EXISTING-COLUMN-NAME NEW-COLUMN-NAME

ALTER TABLE EMPLOYEES
CHANGE FNAME FIRST_NAME VARCHAR(40),
CHANGE LNAME LAST_NAME VARCHAR(40);

-- HOW TO DROP A COLUMN
-- SYNTAX
-- ALTER TABLE TABLE_NAME DROP COLUMN COLUMN_NAME

ALTER TABLE EMPLOYEES DROP COLUMN COMPANY_NAME,
DROP COLUMN PFID;

-- HOW TO CHANGE TABLE-NAME
-- SYNTAX

-- ALTER TABLE TABLE_NAME RENAME TO NEW_TABLE_NAME;

ALTER TABLE EMPLOYEES RENAME TO PRASHUEMP;
ALTER TABLE PRASHUEMP RENAME TO EMPLOYEES;


CREATE TABLE COMPANY_STAFF(
EMPID INT,
AGE TINYINT,
EXPERIENCE SMALLINT,
GENDER CHAR(1),
EMP_NAME VARCHAR(50),
ADDRESS TINYTEXT,
SALARY DECIMAL(10,2),
DEPARTMENT ENUM('HR','IT','SALES','FINANCE','SUPPORT'),
SKILLS SET('JAVA','PYTHON','SQL','EXCEL','COMMUNICATION'),
JOINING_DATE DATE
);

ALTER TABLE COMPANY_STAFF ADD EMAIL VARCHAR(100);

ALTER TABLE COMPANY_STAFF ADD PHONENUMBER BIGINT;

ALTER TABLE COMPANY_STAFF ADD BONUS DECIMAL(8,2) AFTER SALARY,
ADD STATUS VARCHAR(20) AFTER DEPARTMENT,
ADD COMPANY_NAME VARCHAR(50) FIRST;

ALTER TABLE COMPANY_STAFF
ADD QUALIFICATION VARCHAR(50) AFTER EMP_NAME,
MODIFY EMP_NAME VARCHAR(100),
MODIFY SALARY DECIMAL(12,2);


ALTER TABLE COMPANY_STAFF
CHANGE EMP_NAME EMPLOYEE_NAME VARCHAR(100),
CHANGE JOINING_DATE DATE_OF_JOINING DATE;


